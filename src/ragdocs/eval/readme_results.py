"""README results block generated from committed files (M15, offline).

Every number comes from ragdocs.eval.report.summarize, the ragdocs.eval.compare paired
functions, the retrieval run's per_question.jsonl and the provenance files named in
ProvenanceInputs. Nothing is computed from a date or from the network, so the block is
reproducible byte for byte. The block sits between BLOCK_START and BLOCK_END in README.md.
"""

import difflib
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ragdocs.config import Settings, get_settings
from ragdocs.eval.compare import (
    PAIRED_METRICS,
    check_comparable,
    count_verdict,
    item_values,
    paired_compare,
)
from ragdocs.eval.format import (
    NOT_AVAILABLE,
    fmt_calls,
    fmt_mean,
    fmt_ms_as_s,
    fmt_rate,
    fmt_tokens,
)
from ragdocs.eval.judge_audit import score_audit
from ragdocs.eval.report import CONTEXT_LABEL, RAGAS_METRICS, summarize
from ragdocs.io_utils import read_json, read_jsonl, read_text

BLOCK_START = "<!-- results:start -->"
BLOCK_END = "<!-- results:end -->"
PIPELINES: tuple[tuple[str, str], ...] = (
    ("baseline", "Baseline RAG"),
    ("corrective", "Corrective RAG"),
    ("self_rag", "Self-RAG"),
)
MODES: tuple[str, ...] = ("dense", "bm25", "hybrid", "hybrid_rerank")
GATE_BASE_MODE = "hybrid"
GATE_MODE = "hybrid_rerank"
SUMMARY_FILE = "summary.md"
RUNS_DIR = "runs"
RETRIEVAL_RUN_GLOB = "retrieval-*"
README_NOTE = (
    "Generated by `py tasks.py readme` from committed files in `results/`; "
    "do not edit between the markers."
)

# (label, summarize() overall field, kind). Fields match scripts/export_results.py for the
# metrics both show; false abstentions, web search used and p95 latency are README-only.
MAIN_ROWS: list[tuple[str, str, str]] = [
    ("Correct answers", "correct", "rate"),
    ("Correct or partial", "correct_or_partial", "rate"),
    ("Citation support", "citation_support", "rate"),
    ("Unanswerable correctly declined", "abstention_correct", "rate"),
    ("Hallucinated on unanswerable", "hallucinated", "rate"),
    ("False abstentions", "false_abstention", "rate"),
    ("First-retrieval hit@5 (like-for-like retrieval)", "first_retrieval_hit@5", "rate"),
    (f"Context hit@5 ({CONTEXT_LABEL})", "context_hit@5", "rate"),
    ("RAGAS faithfulness", "ragas_faithfulness", "mean"),
    ("RAGAS response relevancy", "ragas_response_relevancy", "mean"),
    (f"RAGAS context precision ({CONTEXT_LABEL})", "ragas_context_precision", "mean"),
    (f"RAGAS context recall ({CONTEXT_LABEL})", "ragas_context_recall", "mean"),
    ("Web search used", "used_web", "rate"),
    ("Mean LLM calls per question", "mean_llm_calls", "calls"),
    ("Mean tokens per question", "mean_tokens_per_question", "tokens"),
    ("Median latency", "latency_ms_p50", "seconds"),
    ("p95 latency", "latency_ms_p95", "seconds"),
]
# Count rows with a difference in questions, and the RAGAS keys of the paired view.
COUNT_ROWS: list[tuple[str, str]] = [(lab, key) for lab, key, kind in MAIN_ROWS if kind == "rate"]
RAGAS_PAIRED = [(key, label) for key, label in PAIRED_METRICS if key in RAGAS_METRICS]
COMPARISONS: tuple[tuple[str, str], ...] = (
    ("corrective", "baseline"),
    ("self_rag", "baseline"),
    ("self_rag", "corrective"),
)
LABELS = dict(PIPELINES)


@dataclass(frozen=True)
class ResultsInputs:
    """Committed files the block is generated from."""

    run_dirs: dict[str, Path]
    retrieval_dir: Path
    manifest_path: Path
    audit_path: Path


def run_names_from_summary(summary_md: Path) -> list[str]:
    """Run folder names in the header row of the first table of results/summary.md."""
    for line in read_text(summary_md).splitlines():
        if line.startswith("| Field |"):
            return [c.strip() for c in line.strip("|").split("|")[1:]]
    raise ValueError(f"No table header row found in {summary_md}")


def default_inputs(settings: Settings | None = None) -> ResultsInputs:
    """Inputs from results/summary.md (run names, in pipeline order) and the settings paths."""
    settings = settings or get_settings()
    runs = settings.results_dir / RUNS_DIR
    names = run_names_from_summary(settings.results_dir / SUMMARY_FILE)
    dirs = {name: runs / run for (name, _), run in zip(PIPELINES, names, strict=True)}
    retrieval = sorted(runs.glob(RETRIEVAL_RUN_GLOB))
    if len(retrieval) != 1:
        raise ValueError(f"Expected one {RETRIEVAL_RUN_GLOB} run in {runs}, found {len(retrieval)}")
    return ResultsInputs(
        run_dirs=dirs,
        retrieval_dir=retrieval[0],
        manifest_path=settings.index_dir / "manifest.json",
        audit_path=settings.results_dir / "judge_audit.md",
    )


def _cell(overall: dict[str, Any], field: str, kind: str) -> str:
    """Format one summarize() overall field for the README table."""
    raw = overall.get(field)
    if raw is None:
        return NOT_AVAILABLE
    if kind == "rate":
        return fmt_rate(raw["count"], raw["n"])
    if kind == "mean":
        return fmt_mean(raw["mean"], raw["n"])
    value = raw["mean"] if isinstance(raw, dict) else raw
    return {"calls": fmt_calls, "tokens": fmt_tokens, "seconds": fmt_ms_as_s}[kind](value)


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    """Markdown table lines."""
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(r) + " |" for r in rows]


def main_results(summaries: dict[str, dict[str, Any]]) -> list[str]:
    """Section (a): one column per pipeline."""
    rows = [
        [label, *(_cell(summaries[name]["overall"], field, kind) for name, _ in PIPELINES)]
        for label, field, kind in MAIN_ROWS
    ]
    n = summaries["baseline"]["overall"]["n"]
    answerable = summaries["baseline"]["overall"]["answerable_n"]
    intro = f"{n} questions ({answerable} answerable, {n - answerable} unanswerable)."
    return ["### Main results", "", intro, ""] + _table(
        ["Metric", *(label for _, label in PIPELINES)], rows
    )


def _verdict_rows(
    summaries: dict[str, dict[str, Any]],
    values: dict[str, dict[str, dict[str, float]]],
    s: Settings,
) -> dict[tuple[str, str], tuple[list[list[str]], list[list[str]]]]:
    """Per comparison: count rows and RAGAS rows."""
    out: dict[tuple[str, str], tuple[list[list[str]], list[list[str]]]] = {}
    for other, base in COMPARISONS:
        counts = []
        for label, key in COUNT_ROWS:
            b, o = summaries[base]["overall"][key], summaries[other]["overall"][key]
            diff = int(round(o["count"] - b["count"]))
            verdict = count_verdict(b["count"], o["count"], s.compare_noise_margin)
            counts.append(
                [
                    label,
                    f"{b['count']:g}",
                    f"{o['count']:g}",
                    f"{diff:+d}" if diff else "0",
                    verdict,
                ]
            )
        ragas = []
        for key, label in RAGAS_PAIRED:
            ids = set.intersection(*(set(v[key]) for v in values.values()))
            r = paired_compare(
                values[base][key],
                values[other][key],
                ids,
                s.compare_paired_threshold,
                s.compare_noise_margin,
            )
            ragas.append([label, str(r.n), str(r.wins), str(r.losses), r.verdict])
        out[(other, base)] = (counts, ragas)
    return out


def verdict_section(
    summaries: dict[str, dict[str, Any]],
    values: dict[str, dict[str, dict[str, float]]],
    s: Settings,
) -> list[str]:
    """Section (b): is the difference real."""
    margin, thr = s.compare_noise_margin, s.compare_paired_threshold
    lines = [
        "### Is the difference real?",
        "",
        f'Counts: a difference under {margin} questions is "no measurable difference" (D19). '
        f"RAGAS: a paired item is a win or loss when its score differs by more than {thr}; "
        f"the verdict needs wins minus losses of at least {margin}, over the items scored in "
        "all three runs. Citation support counts judged items, and the judged n differs "
        "between runs.",
    ]
    for (other, base), (counts, ragas) in _verdict_rows(summaries, values, s).items():
        lines += ["", f"#### {LABELS[other]} vs {LABELS[base]}", ""]
        lines += _table(
            ["Count metric", LABELS[base], LABELS[other], "Difference (questions)", "Verdict"],
            counts,
        )
        lines += [""] + _table(["RAGAS metric", "Paired n", "Wins", "Losses", "Verdict"], ragas)
    return lines


@dataclass(frozen=True)
class ModeStats:
    """Retrieval ablation sums over the answerable questions for one mode."""

    n: int
    hit_at_1: float
    hit_at_5: float
    mrr: float
    evidence_recall_at_5: float


def ablation_stats(retrieval_dir: Path) -> tuple[dict[str, ModeStats], float, int]:
    """Per-mode sums from per_question.jsonl, plus candidate hit@20 sum and its n."""
    rows = read_jsonl(retrieval_dir / "per_question.jsonl")
    stats = {}
    for mode in MODES:
        modes = [r["modes"][mode] for r in rows]
        stats[mode] = ModeStats(
            n=len(rows),
            hit_at_1=sum(m["hit_at_1"] for m in modes),
            hit_at_5=sum(m["hit_at_5"] for m in modes),
            mrr=sum(m["mrr"] for m in modes),
            evidence_recall_at_5=sum(m["evidence_recall_at_5"] for m in modes),
        )
    return stats, sum(r["candidate_hit_at_20"] for r in rows), len(rows)


def gate_sentence(stats: dict[str, ModeStats], min_gain: int) -> str:
    """The D6 gate result with its numbers."""
    base, rerank = stats[GATE_BASE_MODE], stats[GATE_MODE]
    gain = round(rerank.hit_at_5 - base.hit_at_5)
    verdict = "PASS" if gain >= min_gain else "FAIL (reranking stays disabled in production)"
    return (
        f"D6 reranker gate: {GATE_MODE} hit@5 is {fmt_rate(rerank.hit_at_5, rerank.n)} against "
        f"{fmt_rate(base.hit_at_5, base.n)} for {GATE_BASE_MODE}, a gain of {gain} "
        f"question{'' if gain == 1 else 's'} (the gate needs at least {min_gain}); hit@1 goes "
        f"from {fmt_rate(base.hit_at_1, base.n)} to {fmt_rate(rerank.hit_at_1, rerank.n)}. "
        f"Result: {verdict}."
    )


def ablation_section(retrieval_dir: Path, s: Settings) -> list[str]:
    """Section (c): retrieval ablation and the gate sentence."""
    stats, cand, n = ablation_stats(retrieval_dir)
    rows = [
        [
            f"`{mode}`",
            fmt_rate(st.hit_at_1, st.n),
            fmt_rate(st.hit_at_5, st.n),
            fmt_mean(st.mrr / st.n, st.n),
            fmt_mean(st.evidence_recall_at_5 / st.n, st.n),
        ]
        for mode, st in stats.items()
    ]
    lines = ["### Retrieval ablation", ""]
    lines += [f"{n} answerable questions, run `{retrieval_dir.name}`.", ""]
    lines += _table(["Mode", "Hit@1", "Hit@5", "MRR", "Evidence recall@5"], rows)
    lines += ["", f"Candidate pool hit@20 (`retrieve_candidates`): {fmt_rate(cand, n)}.", ""]
    return lines + [gate_sentence(stats, s.rerank_gate_min_gain)]


def provenance_line(inputs: ResultsInputs, summaries: dict[str, dict[str, Any]]) -> str:
    """Section (d): eval set, corpus commit, judge and audit, RAGAS."""
    base_dir = inputs.run_dirs["baseline"]
    config = read_json(base_dir / "config.json")
    ragas = read_json(base_dir / "ragas_config.json")
    judge = summaries["baseline"]["judge"]
    audit = score_audit(base_dir, inputs.audit_path)
    corpus = read_json(inputs.manifest_path)["source_commit"]
    return (
        f"Provenance: {summaries['baseline']['overall']['n']} questions, eval set "
        f"`{config['settings']['eval_set_tag']}` (sha256 `{config['eval_set_sha256']}`); "
        f"corpus commit `{corpus}`; judge {judge['judge_model']}, prompt version "
        f"{judge['effective_prompt_version']}, audit agreement on {audit.n} items: correctness "
        f"{audit.correctness_agree}/{audit.n}, citation support "
        f"{audit.citation_agree}/{audit.n}; RAGAS {ragas['ragas_version']} with "
        f"{ragas['llm_model']}."
    )


def build_block(inputs: ResultsInputs, settings: Settings | None = None) -> str:
    """The full block between the markers, without the markers, ending in one newline."""
    settings = settings or get_settings()
    summaries = {name: summarize(d) for name, d in inputs.run_dirs.items()}
    for name, summary in summaries.items():
        if summary["pipeline"] != name:
            raise ValueError(f"{inputs.run_dirs[name]} is pipeline {summary['pipeline']!r}")
    check_comparable(list(summaries.values()))
    values = {name: item_values(d) for name, d in inputs.run_dirs.items()}
    parts = [
        [README_NOTE, ""],
        main_results(summaries),
        verdict_section(summaries, values, settings),
        ablation_section(inputs.retrieval_dir, settings),
        [provenance_line(inputs, summaries)],
    ]
    return "\n\n".join("\n".join(p).strip("\n") for p in parts) + "\n"


def normalise(text: str) -> str:
    """Line endings to LF."""
    return text.replace("\r\n", "\n")


def extract_block(readme: str) -> str | None:
    """Text between the markers (without them), or None when a marker is missing."""
    start, end = readme.find(BLOCK_START), readme.find(BLOCK_END)
    if start < 0 or end < start:
        return None
    return readme[start + len(BLOCK_START) : end].strip("\n") + "\n"


def replace_block(readme: str, block: str) -> str:
    """README text with the marked region replaced by block; markers are added if missing."""
    readme = normalise(readme)
    if extract_block(readme) is None:
        base = readme.rstrip("\n")
        base = base + "\n\n" if base else ""
        readme = f"{base}## Results\n\n{BLOCK_START}\n{BLOCK_END}\n"
    start, end = readme.find(BLOCK_START), readme.find(BLOCK_END)
    return f"{readme[:start]}{BLOCK_START}\n{block}{readme[end:]}"


def check_readme(readme: str, block: str) -> str | None:
    """None when the README block equals block; else a unified diff or a missing-marker note."""
    current = extract_block(normalise(readme))
    if current is None:
        return f"README.md has no {BLOCK_START} / {BLOCK_END} markers.\n"
    if current == block:
        return None
    diff = difflib.unified_diff(
        current.splitlines(keepends=True),
        block.splitlines(keepends=True),
        fromfile="README.md (current)",
        tofile="README.md (generated)",
    )
    return "".join(diff)


def run(
    readme_path: Path,
    inputs: ResultsInputs,
    check: bool,
    out: Callable[[str], None] = print,
) -> int:
    """Write or check the README block; returns the exit code."""
    block = build_block(inputs)
    exists = readme_path.is_file()
    text = readme_path.read_bytes().decode("utf-8") if exists else ""
    if check:
        problem = check_readme(text, block)
        if problem is None:
            out("README results block is up to date.")
            return 0
        out(problem)
        return 1
    readme_path.write_bytes(replace_block(text, block).encode("utf-8"))
    out(f"Wrote {readme_path.name}")
    return 0
